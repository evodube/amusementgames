#!/usr/bin/env python3
"""Writes src/sim/Collision.inc: the machines' collision triangles (machine space), from tools/collision/*.json.

The JSON is exported from Nuka-World's own models' Havok collision with Blender + PyNifly (the models pulled out of
DLCNukaWorld - Main.ba2; see docs/HANDOFF.md): every triangle of the bhkPhysicsSystem meshes, world space of the
model, three [x, y, z] corners each.

    python tools/collision_to_cpp.py

Hoop Shot's rim (eight flat plates at the hoop's height) and its bracket are left out: the physics has its own round
rim there (sim/Layouts.cpp BuildHoop).
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "sim", "Collision.inc")


def hoop_rim(tri):
    # the rim's plates and the bracket: flat at the hoop's height, round its middle
    return all(153.5 <= v[2] <= 156.5 and abs(v[0]) < 22 and 103 < v[1] < 158 for v in tri)


def emit(name, tris):
    lines = [f"inline constexpr double {name}[][9] = {{"]
    for t in tris:
        lines.append("\t{ " + ", ".join(f"{c:.2f}" for v in t for c in v) + " },")
    lines.append("};")
    return "\n".join(lines)


def main():
    rollers = json.load(open(os.path.join(HERE, "collision", "rollers.json")))
    hoop = [t for t in json.load(open(os.path.join(HERE, "collision", "hoop.json"))) if not hoop_rim(t)]
    with open(OUT, "w", newline="\n") as f:
        f.write("// Generated by tools/collision_to_cpp.py from Nuka-World's models' collision: don't edit.\n")
        f.write("#pragma once\n\nnamespace sim::collision\n{\n")
        f.write(emit("kRollers", rollers) + "\n\n")
        f.write(emit("kHoop", hoop) + "\n")
        f.write("}\n")
    print(f"rollers {len(rollers)} triangles, hoop {len(hoop)}")


if __name__ == "__main__":
    main()
