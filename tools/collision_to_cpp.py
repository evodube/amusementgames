#!/usr/bin/env python3
"""Writes src/sim/Collision.inc: the machines' collision triangles (machine space), from tools/collision/*.json.

The JSON is exported from Nuka-World's own models' Havok collision with Blender + PyNifly (the models pulled out of
DLCNukaWorld - Main.ba2; see docs/HANDOFF.md): every triangle of the bhkPhysicsSystem meshes, world space of the
model, three [x, y, z] corners each.

    python tools/collision_to_cpp.py

Hoop Shot's rim (eight flat plates at the hoop's height) and its bracket are left out: the physics has its own round
rim there (sim/Layouts.cpp BuildHoop). Its return ramp's one flat sheet is swapped for the ramp as you see it.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "sim", "Collision.inc")


def hoop_rim(tri):
    # the rim's plates and the bracket: flat at the hoop's height, round its middle
    return all(153.5 <= v[2] <= 156.5 and abs(v[0]) < 22 and 103 < v[1] < 158 for v in tri)


def hoop_ramp(tri):
    # the model's return ramp: one flat sheet, straight from the front (y -101.7, z 47.5) to the back (169.1, 94.3)
    return all(abs(v[0]) > 55 for v in tri[:1]) and sorted(round(v[1], 1) for v in tri) in ([-101.7, -101.7, 169.1], [-101.7, 169.1, 169.1]) \
        and all(47 < v[2] < 95 for v in tri)


# ...its ramp as you see it (the model's own mesh, L2_Parts:174): a flat foot at the front, a gentle slope up to the
# middle, a steeper one to the back. The flat sheet ran above it, up to 10 units in the middle, and the balls coming
# back down floated over it. (y, z) along it, the whole width of the cage
HOOP_RAMP = [(-101.7, 47.81), (-90.5, 47.81), (-56.1, 48.0), (53.6, 62.84), (163.2, 91.69), (169.1, 93.24)]
HOOP_RAMP_X = (-56.0, 55.9)


def hoop_ramp_tris():
    x0, x1 = HOOP_RAMP_X
    tris = []
    for (ya, za), (yb, zb) in zip(HOOP_RAMP, HOOP_RAMP[1:]):
        # (wound as the model's: facing up)
        tris.append([[x1, yb, zb], [x0, yb, zb], [x0, ya, za]])
        tris.append([[x1, yb, zb], [x0, ya, za], [x1, ya, za]])
    return tris


def emit(name, tris):
    lines = [f"inline constexpr double {name}[][9] = {{"]
    for t in tris:
        lines.append("\t{ " + ", ".join(f"{c:.2f}" for v in t for c in v) + " },")
    lines.append("};")
    return "\n".join(lines)


def main():
    rollers = json.load(open(os.path.join(HERE, "collision", "rollers.json")))
    hoop = [t for t in json.load(open(os.path.join(HERE, "collision", "hoop.json"))) if not hoop_rim(t)]
    ramp = [t for t in hoop if hoop_ramp(t)]
    assert len(ramp) == 2, ramp
    hoop = [t for t in hoop if not hoop_ramp(t)] + hoop_ramp_tris()
    with open(OUT, "w", newline="\n") as f:
        f.write("// Generated by tools/collision_to_cpp.py from Nuka-World's models' collision: don't edit.\n")
        f.write("#pragma once\n\nnamespace sim::collision\n{\n")
        f.write(emit("kRollers", rollers) + "\n\n")
        f.write(emit("kHoop", hoop) + "\n")
        f.write("}\n")
    print(f"rollers {len(rollers)} triangles, hoop {len(hoop)}")


if __name__ == "__main__":
    main()
